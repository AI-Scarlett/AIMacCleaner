def upload_screenshots(api: ASC, localization_id: str) -> None:
    files = sorted(SCREENSHOT_DIR.glob("*.png"))
    if len(files) != 5: raise RuntimeError(f"Expected 5 screenshots in {SCREENSHOT_DIR}, found {len(files)}")
    set_id = screenshot_set(api, localization_id)
    for item in api.json("GET", f"/appScreenshotSets/{set_id}/appScreenshots", params={"limit": 50})["data"]:
        api.json("DELETE", f"/appScreenshots/{item['id']}")
    for path in files:
        data = path.read_bytes()
        created = api.json("POST", "/appScreenshots", ok=(201,), json=body("appScreenshots", attributes={"fileName": path.name, "fileSize": len(data)}, relationships={"appScreenshotSet": rel("appScreenshotSets", set_id)}))
        screenshot_id = created["data"]["id"]
        for operation in created["data"]["attributes"].get("uploadOperations") or []:
            offset = int(operation.get("offset") or 0)
            length = int(operation.get("length") or len(data))
            headers = {header["name"]: header["value"] for header in operation.get("requestHeaders", [])}
            response = requests.request(operation["method"], operation["url"], headers=headers, data=data[offset:offset + length], timeout=180)
            if response.status_code // 100 != 2: raise RuntimeError(f"Screenshot upload failed: {response.status_code} {response.text[:500]}")
        api.json("PATCH", f"/appScreenshots/{screenshot_id}", json=body("appScreenshots", screenshot_id, {"sourceFileChecksum": hashlib.md5(data).hexdigest(), "uploaded": True}))
        print(f"Uploaded {path.name}")


def submit(api: ASC, version_id: str) -> None:
    existing = api.json("GET", "/reviewSubmissions", params={"filter[app]": APP_ID, "filter[platform]": "IOS", "limit": 20})["data"]
    submission = next((item for item in existing if item["attributes"].get("state") in {"READY_FOR_REVIEW", "UNRESOLVED_ISSUES"}), None)
    if not submission:
        submission = api.json("POST", "/reviewSubmissions", ok=(201,), json=body("reviewSubmissions", attributes={"platform": "IOS"}, relationships={"app": rel("apps", APP_ID)}))["data"]
    items = api.json("GET", f"/reviewSubmissions/{submission['id']}/items", params={"limit": 100})["data"]
    if not any(item.get("relationships", {}).get("appStoreVersion", {}).get("data", {}).get("id") == version_id for item in items):
        api.json("POST", "/reviewSubmissionItems", ok=(201,), json=body("reviewSubmissionItems", relationships={"reviewSubmission": rel("reviewSubmissions", submission["id"]), "appStoreVersion": rel("appStoreVersions", version_id)}))
    result = api.json("PATCH", f"/reviewSubmissions/{submission['id']}", json=body("reviewSubmissions", submission["id"], {"submitted": True}))["data"]
    print(f"Submitted review {result['id']}: {result['attributes'].get('state')}")


