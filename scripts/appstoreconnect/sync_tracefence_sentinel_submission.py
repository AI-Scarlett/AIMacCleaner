    parser.add_argument("--skip-screenshots", action="store_true")
    parser.add_argument("--submit", action="store_true")
    args = parser.parse_args()
    key_path = Path.home() / f".appstoreconnect/private_keys/AuthKey_{KEY_ID}.p8"
    if not key_path.exists():
        print(f"Missing API key: {key_path}", file=sys.stderr)
        return 2
    api = ASC(key_path)
    version_id, info_id, build_id = resources(api)
    print(f"Resolved version={version_id} build={build_id}")
    en_localization_id = sync_localizations(api, version_id, info_id)
    sync_version(api, version_id, info_id, build_id)
    ensure_free_pricing(api)
    if not args.skip_screenshots: upload_screenshots(api, en_localization_id)
    if args.submit: submit(api, version_id)
    print("App Privacy answers must be verified in App Store Connect before submission.")
    return 0


