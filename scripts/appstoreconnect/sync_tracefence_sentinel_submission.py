def ensure_free_pricing(api: ASC) -> None:
    try:
        current_prices = api.json(
            "GET", f"/appPriceSchedules/{APP_ID}/manualPrices", params={"limit": 200}
        )["data"]
        if current_prices:
            print("Free app pricing already configured")
            return
    except RuntimeError as error:
        if "-> 404:" not in str(error):
            raise

    points = api.json(
        "GET", f"/apps/{APP_ID}/appPricePoints",
        params={"filter[territory]": "USA", "include": "territory", "limit": 200},
    )["data"]
    free_point = next(
        (item for item in points if float(item["attributes"].get("customerPrice") or -1) == 0),
        None,
    )
    if free_point is None:
        raise RuntimeError("No free USA app price point is available")
    placeholder = "${freeprice-0}"
    payload = body(
        "appPriceSchedules", attributes={},
        relationships={
            "app": rel("apps", APP_ID),
            "manualPrices": {"data": [{"type": "appPrices", "id": placeholder}]},
            "baseTerritory": rel("territories", "USA"),
        },
    )
    payload["included"] = [{
        "type": "appPrices",
        "id": placeholder,
        "attributes": {"startDate": None, "endDate": None},
        "relationships": {"appPricePoint": rel("appPricePoints", free_point["id"])},
    }]
    try:
        api.json("POST", "/appPriceSchedules", ok=(201,), json=payload)
        print("Configured the iOS app as free")
    except RuntimeError as error:
        if "PRICE_ALREADY_EXISTS" in str(error) or "already exists" in str(error).lower():
            print("Free app pricing already configured")
            return
        raise


