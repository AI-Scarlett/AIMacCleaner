def b64url(value: bytes) -> str:
    return base64.urlsafe_b64encode(value).rstrip(b"=").decode()


def token(key_path: Path) -> str:
    key = serialization.load_pem_private_key(key_path.read_bytes(), password=None)
    now = int(time.time())
    header = {"alg": "ES256", "kid": KEY_ID, "typ": "JWT"}
    claims = {"iss": ISSUER_ID, "iat": now, "exp": now + 1200, "aud": "appstoreconnect-v1"}
    message = f"{b64url(json.dumps(header, separators=(',', ':')).encode())}.{b64url(json.dumps(claims, separators=(',', ':')).encode())}".encode()
    signature = key.sign(message, ec.ECDSA(hashes.SHA256()))
    r_value, s_value = utils.decode_dss_signature(signature)
    return f"{message.decode()}.{b64url(r_value.to_bytes(32, 'big') + s_value.to_bytes(32, 'big'))}"


class ASC:
    def __init__(self, key_path: Path) -> None:
        self.key_path = key_path
        self.base = "https://api.appstoreconnect.apple.com/v1"
        self.session = requests.Session()
        self.refresh()

    def refresh(self) -> None:
        self.session.headers.update({"Authorization": f"Bearer {token(self.key_path)}", "Content-Type": "application/json"})

    def json(self, method: str, path: str, ok: tuple[int, ...] = (200, 201, 204), **kwargs: Any) -> dict[str, Any]:
        for attempt in range(6):
            response = self.session.request(method, self.base + path, timeout=180, **kwargs)
            if response.status_code == 401 and attempt == 0:
                self.refresh()
                continue
            if response.status_code == 429 and attempt < 5:
                time.sleep(max(float(response.headers.get("Retry-After", "1")), 1))
                continue
            if response.status_code not in ok:
                raise RuntimeError(f"{method} {path} -> {response.status_code}: {response.text[:2000]}")
            return response.json() if response.text else {}
        raise RuntimeError(f"{method} {path} exhausted retries")


def body(resource_type: str, resource_id: str | None = None, attributes: dict[str, Any] | None = None, relationships: dict[str, Any] | None = None) -> dict[str, Any]:
    data: dict[str, Any] = {"type": resource_type}
    if resource_id: data["id"] = resource_id
    if attributes is not None: data["attributes"] = attributes
    if relationships is not None: data["relationships"] = relationships
    return {"data": data}


def rel(resource_type: str, resource_id: str) -> dict[str, Any]:
    return {"data": {"type": resource_type, "id": resource_id}}


def first(api: ASC, path: str, params: dict[str, Any] | None = None) -> dict[str, Any]:
    items = api.json("GET", path, params=params or {}).get("data") or []
    if not items: raise RuntimeError(f"No resource at {path}")
    return items[0]


