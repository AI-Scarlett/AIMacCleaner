def localization_ids(api: ASC, path: str) -> dict[str, str]:
    return {item["attributes"]["locale"]: item["id"] for item in api.json("GET", path, params={"limit": 100})["data"]}


def upsert_localization(api: ASC, locale: str, resource_type: str, collection_path: str, parent_path: str,
                        relationship_name: str, parent_resource_type: str, parent_id: str,
                        attributes: dict[str, Any]) -> str:
    ids = localization_ids(api, parent_path)
    if locale in ids:
        resource_id = ids[locale]
        api.json("PATCH", f"/{resource_type}/{resource_id}", json=body(resource_type, resource_id, attributes))
        return resource_id

    try:
        created = api.json(
            "POST", collection_path, ok=(201,),
            json=body(resource_type, attributes={"locale": locale, **attributes},
                      relationships={relationship_name: rel(parent_resource_type, parent_id)}),
        )
        return created["data"]["id"]
    except RuntimeError as error:
        if "ATTRIBUTE.INVALID.DUPLICATE" not in str(error):
            raise
        ids = localization_ids(api, parent_path)
        if locale not in ids:
            raise
        resource_id = ids[locale]
        api.json("PATCH", f"/{resource_type}/{resource_id}", json=body(resource_type, resource_id, attributes))
        return resource_id


